export function formatCountryName(
  country: string | null | undefined,
  iso3: string | null | undefined,
  lang: Lang,
): string {
  const fallback = country || "—";
  if (!iso3) return fallback;

  const code = iso3.trim().toUpperCase();

  // Special overrides take highest priority (political names)
  if (COUNTRY_NAME_OVERRIDES[code]) {
    return COUNTRY_NAME_OVERRIDES[code][lang];
  }

  // For English: look up ISO3_TO_EN table
  if (lang === "en" && ISO3_TO_EN[code]) {
    return ISO3_TO_EN[code];
  }

  // Fallback: use the stored country field (Chinese for zh, raw for en)
  return fallback;
}
