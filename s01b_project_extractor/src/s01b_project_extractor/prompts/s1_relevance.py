"""S1 相关性 + 中企参与门 prompt：只判 RE 相关性与是否有中企，强化 B.1 排除规则。"""

from s01b_project_extractor.prompts.policy_fragments import CHINESE_IDENTITY_RULE, ENTITY_POLICY_VERSION, MANUFACTURING_SCOPE_RULE, RECORD_TYPE_RULE


def build_s1_prompt(title: str, content: str, date: str) -> str:
    """构建 S1 门控 prompt：输出 {status, reasoning, project_subject, is_power_generation_plant}。"""
    return f"""提示词版本：{ENTITY_POLICY_VERSION}
你是一个能源新闻相关性审核专家。请按下面的【两步决策】初筛这篇新闻，按输出格式给出结论。**不要提取项目明细。**

文章发布日期：{date}
文章标题：{title}
文章正文：
{content[:12000]}
(内容截断)

### 两步决策（务必严格按顺序）

**第一步：这篇新闻是否属于以下三类「录入范围」之一？**（含为其招标/拍卖/签约/中标/建设/供货/投融资/并网等任一环节）
- ① **电力项目（发电或独立储能）**：光伏、风电、水电、火电、核电、生物质、地热、综合能源等发电厂/电站，以及明确的独立储能项目。独立储能是合法 Category，但**不是发电源**。
- ② **新能源制造业**：以产能计的新能源装备或材料工厂——光伏组件、锂电池/储能系统、多晶硅、新能源装备产业园等。{MANUFACTURING_SCOPE_RULE}
- ③ **输变电/电网工程**：独立输电线路、变电站、电网改造、供电工程等。发电项目内部的配套升压站和送出线路属于发电项目范围，**不得另拆为 TX 项目**。
- {RECORD_TYPE_RULE}
- 上述范围的设备订单、一般合作也进第二步，由S2标明非项目记录类型。
- 命中①②③任一 → 进第二步。若属于以下情形（**不在范围**）→ 直接 status = "irrelevant"（**与是否有中企无关**）：
  1. 非发电的基建/民用/用电户：学校、医院、机场、铁路、港口、灌溉、供水管网、住宅、数据中心、（不以产能计的）普通工业园区本身等。例外：「为其配套自建的发电电站」本身进第二步。
  2. 油气/矿业的非发电环节：油气田开采、炼油炼化、油气管道、LNG 接收/储运站、采矿、冶炼等本身不发电的环节，以及**矿产/化肥/化工/冶金/建材产品的开采、生产与加工本身**（钾肥/钾盐矿、铜金矿、氧化铝、甲醇、水泥、钢铁等，即使以「万吨/年」计产能）。例外：上述制造业口径已确认纳入的锂资源/电池材料等项目，以及燃气电厂、煤电厂、核电厂、垃圾/生物质发电厂等**发电项目**进第二步。
  3. 仅检修/维护/改造既有设施且无新增装机容量。
  4. 仅一般产品宣传或市场进入，既无实质设备订单/供货、又无具名各方的实质能源合作。总量级设备订单本身保留，不能因缺电站名称排除。
  5. 纯评论/综述/榜单，无具体项目节点。
  6. 纯领导访问/会议/视察且**无任何具体项目节点**。例外：含具体签约/中标/开工/并网节点（有项目名或电站）则进第二步。
  7. **绿氢/绿氨/电解水制氢项目**：标题或正文明确给出目标项目的**可再生能源发电种类**（光伏/风电/水电/地热等）时进第二步。标题属于本篇证据，不能因正文只用简称否定标题。实质制氢设备订单按订单边界纳入，不要求披露基地装机MW，不将1000方级等设备能力换成MW；普通化肥生产和其他项目背景仍不纳入。只提「绿氢/电解」而无明确能源种类 → irrelevant。
  8. **批量招标计划/国家能源规划/企业远期目标**：通篇仅描述"某国此轮招标 N 个地块/轮次公告本身"（未指向任何具体可识别电站）、"某国 2030 年达到 X GW 装机目标"式国家规划、或"某公司未来 X 年拟开发 X GW"式战略愿景，**不指向任何可识别单体项目** → irrelevant。⚠️ 若文章同时含具体电站名/中标具体标段，则仍进第二步（招标/中标新闻只要指向具体单体项目即照常收录）。
- 不确定是否在范围内时，**存疑倾向算**（recall-first，宁可多收再筛）。

**第二步：在上述录入范围项目中，是否有中国企业参与？**（业主/承包商/设备商/投资方/融资方等任一）
- 先列出目标项目具名参与者（包括英文品牌），再逐个判断身份。不得因为英文名、没有“中国”字样或未入名录跳过它；常见品牌知识可直接使用。不能确定国籍的具名设备商/承包商属于待提取候选，不是no_chinese的证据。
- 有中企且给出具体公司名 → status = "valid_project"。
- 明确有中国企业参与（中标/承建/融资/EPC 等）但通篇未给出具体公司名 → status = "chinese_unnamed_participation"。
- 无中企（标题和正文均无任何中国企业，或各环节参与者均非中企）→ status = "no_chinese_participation"。
- ⚠️ **关键规则**：一篇「确是电力/发电项目、但没有中企参与」的新闻，**必须**判 "no_chinese_participation"，**绝不可**判 "irrelevant"。"irrelevant" 仅用于第一步判定的范围外主题。
- 注意识别中方企业的简称、曾用名、子公司名（如「中材节能」属中国建材集团）。
- 本步不查询完整企业登记册；有具名参与企业且中企身份可能成立但尚不确定时，保留为 valid_project 交后续逐实体核实，不能因陌生名称/简称不熟悉判 no_chinese_participation。valid_project 是提取候选，不代表已经通过发布。
- 中企身份边界：{CHINESE_IDENTITY_RULE}
- 例：「该光伏项目由一家中国企业中标承建」（未点名）→ chinese_unnamed_participation；「中国电建中标」（点名）→ valid_project；「设备由中国厂商供应」但通篇无具名中企 → chinese_unnamed_participation。

### 输出格式（严格 JSON，仅这些字段）
{{
  "status": "valid_project | chinese_unnamed_participation | no_chinese_participation | irrelevant",
  "project_subject": "一句话点明新闻主体（什么项目/什么主体）",
  "is_power_generation_plant": true | false,
  "candidate_entities": [{{"name": "目标项目原文参与者（含英文名）", "chinese_likelihood": "likely|uncertain|non_chinese", "reason": "身份及目标项目参与判断"}}],
  "reasoning": "判定理由：第一步命中哪条→irrelevant，或第二步有/无/未具名中企→valid/chinese_unnamed/no_chinese（简短）"
}}
"""
